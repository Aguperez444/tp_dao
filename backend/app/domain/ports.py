"""Contratos que la aplicación necesita; no dependen de FastAPI ni SQLAlchemy."""
from typing import Any, Protocol

Record = dict[str, Any]


class Repository(Protocol):
    def get(self, table: str, id: int) -> Record | None: ...
    def list(self, table: str, **filters: Any) -> list[Record]: ...
    def create(self, table: str, data: Record) -> Record: ...
    def update(self, table: str, id: int, data: Record) -> Record: ...
    def stock(self, establishment: int, product: int) -> Record: ...
    def returned(self, sale: int, product: int) -> int: ...


class UnitOfWork(Protocol):
    repo: Repository
    def __enter__(self) -> 'UnitOfWork': ...
    def __exit__(self, exc_type, exc, traceback) -> None: ...
